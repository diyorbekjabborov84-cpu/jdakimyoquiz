import { resolve } from "node:path";
import type { Quiz } from "./types.js";

type QuestionRow = [
  question: string,
  correct: string,
  distractor1: string,
  distractor2: string,
  distractor3: string,
  diagram?: string,
];

function makeQuiz(id: string, title: string, scope: string, rows: QuestionRow[]): Quiz {
  return {
    id,
    title,
    description: `8-sinf kimyo, ${scope} · ${rows.length} savol`,
    source: "I. Asqarov, K. G‘opirov, N. To‘xtaboyev. Kimyo-8, 2019-yilgi 4-nashr",
    bolim: "kimyo_8",
    groupOnly: true,
    shuffle: true,
    questions: rows.map(([question, correct, first, second, third, diagram], index) => ({
      id: `${id}_${index + 1}`,
      question,
      options: [correct, first, second, third],
      correctOptionId: 0,
      timeLimitSeconds: diagram ? 30 : 20,
      ...(diagram && { imagePath: resolve(__dirname, "../../assets/grade8-chemistry", `${diagram}.png`) }),
    })),
  };
}

